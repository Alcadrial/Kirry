package com.alcadrial.renderengine.render.textures;

public class TextureTemplateException extends RuntimeException {
	
	public TextureTemplateException()
	{
		
	}
	
	public TextureTemplateException(String message)
	{
		super(message);
	}
	
	public TextureTemplateException(Throwable cause)
	{
		super(cause);
	}
	
	public TextureTemplateException(String message, Throwable cause)
	{
		super(message, cause);
	}
	
	public TextureTemplateException(String message, Throwable cause, boolean enableSuppression, boolean writableStackTrace)
	{
		super(message, cause, enableSuppression, writableStackTrace);
	}
}
